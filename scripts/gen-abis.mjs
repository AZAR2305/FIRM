// Generates typed ABI modules from Foundry artifacts so TypeScript always matches the contracts.
//   forge build (in contracts/) && node scripts/gen-abis.mjs
import { readFileSync, writeFileSync, mkdirSync, existsSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const out = join(root, "contracts", "out");
const dest = join(root, "backend", "shared", "src", "abis");

// [artifact file, contract name]
const WANTED = [
  ["Scoreboard.sol", "Scoreboard"],
  ["FirmRouter.sol", "FirmRouter"],
  ["RawRouter.sol", "RawRouter"],
  ["CanaryRunner.sol", "CanaryRunner"],
  ["ProbeSender.sol", "ProbeSender"],
  ["MockToken.sol", "MockToken"],
  ["IV4Quoter.sol", "IV4Quoter"],
  ["IPoolManager.sol", "IPoolManager"],
];

mkdirSync(dest, { recursive: true });
const exported = [];
for (const [file, name] of WANTED) {
  const p = join(out, file, `${name}.json`);
  if (!existsSync(p)) {
    console.warn(`skip ${name}: ${p} not found (run forge build)`);
    continue;
  }
  const { abi } = JSON.parse(readFileSync(p, "utf8"));
  writeFileSync(
    join(dest, `${name}.ts`),
    `// GENERATED by scripts/gen-abis.mjs from Foundry artifacts. Do not edit.\nexport const ${name}Abi = ${JSON.stringify(abi, null, 2)} as const;\n`,
  );
  exported.push(name);
}
writeFileSync(
  join(dest, "index.ts"),
  `// GENERATED by scripts/gen-abis.mjs. Do not edit.\n${exported.map((n) => `export { ${n}Abi } from "./${n}";`).join("\n")}\n`,
);
console.log(`wrote ${exported.length} ABIs to backend/shared/src/abis`);
