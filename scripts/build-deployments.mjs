// Assembles deployments/10143.json (single source of truth for addresses) and docs/DEPLOYMENTS.md from the Foundry
// stage files and broadcast receipts. Run automatically by contracts/script/Redeploy.sh.
import { writeFileSync } from "node:fs";
import { buildModel, OUT_JSON, OUT_MD, IS_FORK } from "./lib/deployments.mjs";

// testnet.monadexplorer.com redirects to MonadVision and keeps the /tx/ and /address/ paths
const EXPLORER = "https://testnet.monadexplorer.com";
const m = buildModel();

writeFileSync(OUT_JSON, JSON.stringify(m, null, 2) + "\n");

const addr = (a) => `[\`${a}\`](${EXPLORER}/address/${a})`;
const tx = (h) => (h ? `[\`${h.slice(0, 10)}...\`](${EXPLORER}/tx/${h})` : "n/a");
const rows = (group) =>
  Object.entries(group)
    .map(([k, e]) => `| ${k} | ${addr(e.address)} | ${tx(e.deployTx)} | ${e.blockNumber ?? "n/a"} | ${e.verification} |`)
    .join("\n");

let md = `# Deployments: Monad Testnet (chain ${m.chainId})

> Generated by \`scripts/build-deployments.mjs\` from \`deployments/10143.json\`. Do not edit by hand.
> Generated at ${m.generatedAt}. Owner / deployer: ${addr(m.owner)}.
>
> Test fixtures below are **quarantined, testnet-only** contracts that misbehave on purpose. They are not
> registered in any hook list and must never be deployed to mainnet.

## Core contracts

| Contract | Address | Deploy tx | Block | Verification |
|---|---|---|---|---|
${rows(m.core)}

Indexer start block: ${m.startBlock ?? "n/a"}.

## Uniswap v4 infrastructure (Monad-maintained testnet deployment, not official)

| Name | Address |
|---|---|
${Object.entries(m.infra)
  .map(([k, a]) => `| ${k} | ${addr(a)} |`)
  .join("\n")}
`;

if (m.fixtures) {
  md += `
## Test fixtures (quarantined)

| Fixture | Address | Deploy tx | Block | Verification |
|---|---|---|---|---|
${rows(m.fixtures)}
`;
}
if (m.pools) {
  md += `
## Seeded pools (tUSD / tUSDC, tick spacing ${m.pools.tickSpacing}, full range)

currency0 \`${m.pools.currency0}\`, currency1 \`${m.pools.currency1}\`; the demo trade tUSD -> tUSDC has zeroForOne = **${m.pools.zeroForOne}**.

| Pool | Description | Hook | Fee | Pool id |
|---|---|---|---|---|
${Object.entries(m.pools.list)
  .map(([n, p]) => `| ${n} | ${p.description} | ${p.hook === "0x0000000000000000000000000000000000000000" ? "none" : addr(p.hook)} | ${p.fee} | \`${p.poolId}\` |`)
  .join("\n")}
`;
}
writeFileSync(OUT_MD, md);
console.log(`wrote ${OUT_JSON} and ${OUT_MD}${IS_FORK ? " (FORK: git-ignored)" : ""}`);
